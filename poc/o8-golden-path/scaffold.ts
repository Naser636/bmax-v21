#!/usr/bin/env node
"use strict";
/*
 * O8 PoC — Internal Developer Platform "golden-path" scaffolder (deterministic, offline, isolated).
 *
 * Demonstrates the GOLDEN-PATH substrate reusing ODG's governed-contract pattern (mirrors
 * mission-contract-factory's declared-input→contract→scope→gates shape) WITHOUT wiring into the live
 * roadmap/runtime and WITHOUT a new primitive. Given a declared template + params, it emits — into an
 * ISOLATED target dir — a deterministic scaffold (files), a mission CONTRACT (objective + authorized
 * write-set), governance-gate placeholders (deny-by-default), and a provenance MANIFEST (sha256 per file).
 * A second run is byte-identical (deterministic). Malformed input / missing authorization fail CLOSED.
 *
 * This is a PoC of the golden-path CONCEPT — NOT a complete IDP product (plugin catalog, CI wiring,
 * multi-stack templates remain SPEC). No network, no new dependency, no runtime mutation.
 *
 * Run: tsx poc/o8-golden-path/scaffold.ts '<json-input>' <targetDir>   (CommonJS idiom; no "type":"module")
 *
 * TS migration (ZERO-JS L-POC): byte-faithful port of scaffold.js; CommonJS require()/module.exports kept.
 * The node-service TEMPLATES still emit .js — those are the SCAFFOLDED PRODUCT's files (written to the
 * caller's isolated target dir / temp dir), not internal repo source, so they are unchanged. No behaviour change.
 */
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const TEMPLATES: Record<string, any> = {
  "node-service": {
    files: {
      "package.json": (p: any) => JSON.stringify({ name: p.name, version: "0.1.0", private: true, scripts: { test: "node test.js" } }, null, 2) + "\n",
      "index.js": (p: any) => `"use strict";\n// ${p.name} — golden-path scaffold\nmodule.exports = { name: ${JSON.stringify(p.name)} };\n`,
      "test.js": () => `"use strict";\nconst assert=require("assert");const m=require("./index.js");assert.ok(m.name);console.log("ok");\n`,
      "README.md": (p: any) => `# ${p.name}\n\nGenerated by the ODG golden-path PoC. Owner: ${p.owner}.\n`,
    },
    writeSet: ["package.json", "index.js", "test.js", "README.md"],
    acceptance: ["files generated match the write-set exactly", "node test.js exits 0", "rerun byte-identical"],
  },
};

function sha256(s: string): string { return crypto.createHash("sha256").update(s).digest("hex"); }

// Governance gate: deny-by-default. An authorization token must grant the exact template + write-set.
function admit(input: any): boolean {
  if (!input || typeof input !== "object") throw new Error("golden-path: malformed input (object required)");
  const { template, name, owner, authorization } = input;
  if (!TEMPLATES[template]) throw new Error(`golden-path: unknown template "${template}" (DENY)`);
  if (typeof name !== "string" || !/^[a-z][a-z0-9-]{1,40}$/.test(name)) throw new Error("golden-path: invalid project name (DENY)");
  if (typeof owner !== "string" || !owner) throw new Error("golden-path: owner required (DENY)");
  // deny-by-default: authorization must explicitly grant this template.
  if (!authorization || authorization.grantTemplate !== template) throw new Error("golden-path: authorization absent/mismatch (DENY, fail-closed)");
  return true;
}

function scaffold(input: any, targetDir: string): any {
  admit(input);
  const t = TEMPLATES[input.template];
  const params = { name: input.name, owner: input.owner };
  const written: string[] = [];
  fs.mkdirSync(targetDir, { recursive: true });
  const manifestEntries: any[] = [];
  for (const rel of t.writeSet) {
    const content = t.files[rel](params);
    const abs = path.join(targetDir, rel);
    fs.writeFileSync(abs, content);
    written.push(rel);
    manifestEntries.push({ path: rel, sha256: sha256(content), bytes: Buffer.byteLength(content) });
  }
  manifestEntries.sort((a: any, b: any) => (a.path < b.path ? -1 : 1));
  const contract = {
    kind: "golden-path-mission-contract/1",
    objective: `scaffold ${input.template} project "${input.name}"`,
    authorizedWriteSet: t.writeSet.map((r: string) => path.join(input.name, r)),
    gates: { authorization: "deny-by-default (granted: " + input.template + ")", acceptance: t.acceptance },
    provenance: { manifest: manifestEntries, generator: "odg-o8-golden-path-poc/1 (deterministic, offline)" },
  };
  return { written: written.sort(), contract };
}

if (require.main === module) {
  const input = JSON.parse(process.argv[2] || "{}");
  const target = process.argv[3] || path.join(__dirname, "out", input.name || "demo");
  const r = scaffold(input, target);
  fs.writeFileSync(path.join(target, ".golden-path-contract.json"), JSON.stringify(r.contract, null, 2));
  process.stdout.write("O8 scaffold: " + r.written.length + " files → " + target + " | writeSet=" + r.contract.authorizedWriteSet.join(",") + "\n");
}
module.exports = { scaffold, admit, TEMPLATES };
export {};
