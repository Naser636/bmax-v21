/*
 * supply-chain-attest — additional lockfile formats (CTO MASTER MANDATE §3): pnpm / yarn / Gemfile / composer.
 * Hermetic: fixtures mirror the REAL formats observed (pnpm v9 `packages:` + a following `snapshots:` that must
 * NOT be double-counted; yarn v1 `version "x"` AND berry `version: x`; scoped names; Gemfile GEM/specs 4-space
 * gems; composer.lock packages + packages-dev). pnpm/yarn install npm-registry packages ⇒ purl type `npm`
 * (dedups with package-lock); gem ⇒ pkg:gem; composer ⇒ pkg:composer. Pure, fail-closed, dual-port .ts≡.js.
 * Run: node_modules/.bin/tsx src/runtime/sbom-lockfile-formats.test.ts
 */
import path from "node:path";
const REPO = process.cwd();
const ts = require(path.join(REPO, "runtime/core/supply-chain-attest.ts"));
const js = require(path.join(REPO, "runtime/core/supply-chain-attest.js"));
let failures = 0;
function check(c: boolean, label: string): void { if (c) console.log(`  PASS ${label}`); else { failures++; console.log(`  FAIL ${label}`); } }
const purls = (comps: any[]) => comps.map((c) => c.purl);

// pnpm v9: `packages:` section (authoritative) + a `snapshots:` section after it that repeats keys ⇒ bounding test.
const PNPM = [
  "lockfileVersion: '9.0'", "", "settings:", "  autoInstallPeers: true", "",
  "packages:", "",
  "  '@bcoe/v8-coverage@1.0.2':", "    resolution: {integrity: sha512-xxx}", "    engines: {node: '>=18'}", "",
  "  caniuse-lite@1.0.30001759:", "    resolution: {integrity: sha512-yyy}", "",
  "  update-browserslist-db@1.2.0(browserslist@4.24.0):", "    resolution: {integrity: sha512-zzz}", "",
  "snapshots:", "",
  "  '@bcoe/v8-coverage@1.0.2': {}", // must NOT be counted again
  "  caniuse-lite@1.0.30001759: {}",
].join("\n");

// yarn v1 (classic) + one berry-style block.
const YARN = [
  "# THIS IS AN AUTOGENERATED FILE.", "# yarn lockfile v1", "",
  '"@ungap/promise-all-settled@1.1.2":', '  version "1.1.2"', '  resolved "https://x/y.tgz#h"', "",
  "align-text@^0.1.1, align-text@^0.1.3:", '  version "0.1.4"', "  dependencies:", '    kind-of "^3.0.2"', "",
  "ansi-colors@4.1.1:", '  version "4.1.1"', "",
  '"berry-pkg@npm:^2.0.0":', "  version: 2.3.1", // berry-style (unquoted version:)
].join("\n");

// Gemfile.lock (Bundler): top-level gems are 4-space `name (version)`; 6-space lines are deps (skipped).
const GEMFILE = [
  "GEM", "  remote: https://rubygems.org/", "  specs:",
  "    actionpack (7.0.4)", "      actionview (= 7.0.4)", "      rack (~> 2.0)",
  "    rake (13.0.6)", "    nokogiri (1.15.5)", "",
  "PLATFORMS", "  ruby", "", "DEPENDENCIES", "  rails", "", "BUNDLED WITH", "   2.4.10",
].join("\n");

// composer.lock (JSON): packages (prod) + packages-dev.
const COMPOSER = JSON.stringify({
  packages: [{ name: "monolog/monolog", version: "3.5.0" }, { name: "symfony/console", version: "v6.4.2" }],
  "packages-dev": [{ name: "phpunit/phpunit", version: "10.5.5" }],
});

console.log("supply-chain-attest — pnpm / yarn / Gemfile / composer (hermetic)");

// pnpm: 3 components from `packages:`; snapshots NOT double-counted; scoped + peer-suffix handled.
const pn = ts.componentsFromManifest(PNPM, "pnpm");
check(pn.length === 3 && purls(pn).includes("pkg:npm/@bcoe/v8-coverage@1.0.2") && purls(pn).includes("pkg:npm/caniuse-lite@1.0.30001759") && purls(pn).includes("pkg:npm/update-browserslist-db@1.2.0"), "pnpm-lock ⇒ 3 npm comps (scoped + peer-suffix stripped; snapshots not double-counted)");

// yarn: 4 components (v1 x3 + berry x1); scoped + name-before-last-@.
const yn = ts.componentsFromManifest(YARN, "yarn");
check(yn.length === 4 && purls(yn).includes("pkg:npm/@ungap/promise-all-settled@1.1.2") && purls(yn).includes("pkg:npm/align-text@0.1.4") && purls(yn).includes("pkg:npm/ansi-colors@4.1.1") && purls(yn).includes("pkg:npm/berry-pkg@2.3.1"), "yarn.lock (v1 + berry) ⇒ 4 npm comps, resolved versions, scoped name kept");

// gem: 3 top-level gems; 6-space deps skipped; other sections ignored.
const gm = ts.componentsFromManifest(GEMFILE, "gem");
check(gm.length === 3 && purls(gm).includes("pkg:gem/actionpack@7.0.4") && purls(gm).includes("pkg:gem/rake@13.0.6") && purls(gm).includes("pkg:gem/nokogiri@1.15.5"), "Gemfile.lock ⇒ 3 gem comps (6-space deps + DEPENDENCIES section skipped)");

// composer: packages + packages-dev; vendor/pkg names; version 'v' prefix preserved.
const cp = ts.componentsFromManifest(COMPOSER, "composer");
check(cp.length === 3 && purls(cp).includes("pkg:composer/monolog/monolog@3.5.0") && purls(cp).includes("pkg:composer/symfony/console@v6.4.2") && purls(cp).includes("pkg:composer/phpunit/phpunit@10.5.5"), "composer.lock ⇒ 3 comps (packages + packages-dev), pkg:composer purls");

// cross-tool dedup: package-lock npm + pnpm of the SAME package ⇒ one component (both pkg:npm).
const NPM = JSON.stringify({ packages: { "node_modules/caniuse-lite": { version: "1.0.30001759" } } });
const merged = ts.buildSbomMulti([{ content: NPM, ecosystem: "npm" }, { content: PNPM, ecosystem: "pnpm" }], { name: "x", version: "0" });
check(merged.components.filter((c: any) => c.purl === "pkg:npm/caniuse-lite@1.0.30001759").length === 1, "buildSbomMulti dedups caniuse-lite across package-lock(npm) + pnpm (both pkg:npm)");

// fail-closed: malformed / unknown / null ⇒ [] (no throw).
let threw = false;
try { check(ts.componentsFromManifest("not: [valid", "pnpm").length === 0 && ts.componentsFromManifest("{bad json", "composer").length === 0 && ts.componentsFromManifest(null, "yarn").length === 0 && ts.componentsFromManifest(GEMFILE, "unknown-eco").length === 0, "malformed/unknown/null ⇒ [] (fail-closed)"); } catch { threw = true; }
check(!threw, "no throw on malformed input");

// dual-port parity (.ts ≡ .js) for every new format.
const sig = (m: any) => JSON.stringify([
  m.componentsFromManifest(PNPM, "pnpm"), m.componentsFromManifest(YARN, "yarn"),
  m.componentsFromManifest(GEMFILE, "gem"), m.componentsFromManifest(COMPOSER, "composer"),
]);
check(sig(ts) === sig(js), "dual-port parity: .ts ≡ .js for pnpm/yarn/gem/composer");

// existing branches unchanged (regression spot-check within this file).
check(ts.componentsFromManifest('[[package]]\nname = "serde"\nversion = "1.0.210"\n', "cargo").length === 1, "existing cargo branch still works (unchanged)");

console.log(`\nsbom-lockfile-formats — ${failures === 0 ? "ALL PASS" : failures + " FAILED"}.`);
process.exit(failures === 0 ? 0 : 1);
