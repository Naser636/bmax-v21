#!/usr/bin/env node
"use strict";
const assert = require("assert");
const P4 = require("./profession-p4-data-reference");
let failures = 0;
function check(c: any, label: any) { if (c) { console.log("  ok -", label); } else { failures++; console.log("  FAIL", label); } assert.ok(c, label); }
console.log("V12.4 §43 P4 — DATA REFERENCE (E2/E3)");

const schema = { id: { type: "string", required: true }, age: { type: "number", min: 0, max: 120, required: true } };

// quality: clean rows ⇒ clean; bad rows ⇒ defects.
{
  check(P4.assessDataQuality([{ id: "a", age: 30 }, { id: "b", age: 50 }], schema).clean === true, "clean rows ⇒ quality clean (score 1)");
  const bad = P4.assessDataQuality([{ id: "a", age: 200 }, { id: "b" }, { id: "a", age: 30 }], schema);
  check(bad.rangeErrors >= 1 && bad.nulls >= 1 && bad.duplicates >= 1 && bad.clean === false, "range violation + null + duplicate ⇒ defects flagged");
}

// lineage fail-closed.
check(P4.checkLineage({ source: "s", transforms: ["t"] }).ok === true && P4.checkLineage({}).ok === false, "lineage: present ⇒ ok; missing ⇒ fail-closed");

// schema compatibility (reuses api-contract): a new required field ⇒ BREAKING.
{
  const compat = P4.schemaCompatibility(schema, Object.assign({}, schema, { email: { type: "string", required: true } }));
  check(compat.compatible === false && compat.breaking.length >= 1, "schema: new required field ⇒ BREAKING (via api-contract)");
  const typeChange = P4.schemaCompatibility(schema, { id: { type: "number", required: true }, age: { type: "number", required: true } });
  check(typeChange.compatible === false, "schema: field type change ⇒ BREAKING");
}

// idempotent replay.
check(P4.idempotentReplay([{ id: "a" }, { id: "b" }]).idempotent === true, "idempotent replay: ingesting twice ⇒ same deduped set");

// E2 reference ⇒ clean, level E2; E3 with a breaking schema ⇒ degraded.
{
  const e2 = P4.runReferenceProject({});
  check(e2.synthetic === true && e2.profession === "P4" && e2.quality.clean === true && e2.level === "E2" && e2.degraded === false, "E2: clean synthetic dataset ⇒ level E2, not degraded");
  const e3 = P4.runReferenceProject({ newSchema: Object.assign({}, schema, { ssn: { type: "string", required: true } }) });
  check(e3.level === "E3" && e3.degraded === true, "E3: breaking schema change ⇒ degradation flagged");
}
check(P4.P4_DATA_REFERENCE_CONTRACT.invariants.some((i: any) => /E5.*owner-gated NOT_RUN/.test(i)), "honesty: SYNTHETIC only, E5 owner-gated NOT_RUN");

// V252 §5 — W3C PROV / OpenLineage provenance-graph validation.
{
  // VALID: raw(source) -> clean (verified run). No violations, no UNKNOWN.
  const good = P4.validateProvenanceGraph({
    datasets: [{ id: "raw", external: true }, { id: "clean" }],
    runs: [{ id: "job1", job: "normalize", used: ["raw"], generated: ["clean"], verified: true }],
  });
  check(good.ok === true && good.violations.length === 0 && good.provenance.verified === 1 && good.trust.raw === "SOURCE" && good.trust.clean === "VERIFIED", "PROV valid: source->verified run ⇒ ok, clean=VERIFIED, raw=SOURCE");
  // DANGLING_REFERENCE: a run uses a dataset not declared.
  const dangling = P4.validateProvenanceGraph({ datasets: [{ id: "clean" }], runs: [{ id: "j", used: ["ghost"], generated: ["clean"], external: false }] });
  check(dangling.ok === false && dangling.violations.some((v: any) => v.code === "DANGLING_REFERENCE"), "PROV: used unknown dataset ⇒ DANGLING_REFERENCE, not ok");
  // AMBIGUOUS_GENERATION: two runs generate the same dataset.
  const ambig = P4.validateProvenanceGraph({ datasets: [{ id: "a", external: true }, { id: "b" }], runs: [{ id: "j1", used: ["a"], generated: ["b"] }, { id: "j2", used: ["a"], generated: ["b"] }] });
  check(ambig.violations.some((v: any) => v.code === "AMBIGUOUS_GENERATION"), "PROV: a dataset generated by two runs ⇒ AMBIGUOUS_GENERATION");
  // CYCLE: x derives from y and y derives from x ⇒ acyclicity violation.
  const cyclic = P4.validateProvenanceGraph({ datasets: [{ id: "x" }, { id: "y" }], runs: [{ id: "jx", used: ["y"], generated: ["x"] }, { id: "jy", used: ["x"], generated: ["y"] }] });
  check(cyclic.violations.some((v: any) => v.code === "CYCLE"), "PROV: mutual derivation ⇒ CYCLE (PROV-CONSTRAINTS acyclicity)");
  // UNKNOWN / fail-closed: a non-source root (no generator, not external) ⇒ UNKNOWN ⇒ never a valid proof.
  const unknown = P4.validateProvenanceGraph({ datasets: [{ id: "mystery" }, { id: "out" }], runs: [{ id: "j", used: ["mystery"], generated: ["out"] }] });
  check(unknown.ok === false && unknown.trust.mystery === "UNKNOWN" && unknown.provenance.unknown >= 1, "PROV fail-closed: non-source root with absent provenance ⇒ UNKNOWN, not ok (absent ≠ valid proof)");
  // DECLARED vs VERIFIED: a plain run is DECLARED only (not counted as verified).
  const declared = P4.validateProvenanceGraph({ datasets: [{ id: "s", external: true }, { id: "d" }], runs: [{ id: "j", used: ["s"], generated: ["d"] }] });
  check(declared.ok === true && declared.trust.d === "DECLARED" && declared.provenance.verified === 0 && declared.verifiedShare === 0, "PROV: a declared (unobserved) derivation is DECLARED, not VERIFIED (declared ≠ verified)");
  // OBSERVED via run.observed, explicit derivation status override wins.
  const observed = P4.validateProvenanceGraph({ datasets: [{ id: "s", external: true }, { id: "d" }], runs: [{ id: "j", used: ["s"], generated: ["d"], observed: true }], derivations: [{ generated: "d", from: "s", status: "VERIFIED" }] });
  check(observed.trust.d === "VERIFIED", "PROV: explicit derivation status (VERIFIED) overrides run flag");
  // traceLineage reconstructs upstream; incomplete when it reaches UNKNOWN.
  const chain = { datasets: [{ id: "raw", external: true }, { id: "clean" }, { id: "agg" }], runs: [{ id: "j1", used: ["raw"], generated: ["clean"] }, { id: "j2", used: ["clean"], generated: ["agg"] }] };
  const trace = P4.traceLineage(chain, "agg");
  check(trace.ok === true && trace.upstream.indexOf("raw") >= 0 && trace.upstream.indexOf("clean") >= 0 && trace.complete === true, "PROV traceLineage: reconstructs agg<-clean<-raw, complete to declared source");
  const traceBad = P4.traceLineage({ datasets: [{ id: "mystery" }, { id: "out" }], runs: [{ id: "j", used: ["mystery"], generated: ["out"] }] }, "out");
  check(traceBad.complete === false, "PROV traceLineage: reaching an UNKNOWN origin ⇒ complete=false (not a trusted provenance)");
  // fail-closed + deterministic.
  check(P4.validateProvenanceGraph({}).code === "EMPTY_GRAPH" && P4.validateProvenanceGraph(null).code === "EMPTY_GRAPH", "PROV fail-closed: empty/malformed graph ⇒ EMPTY_GRAPH (no throw)");
  check(JSON.stringify(P4.validateProvenanceGraph(good.datasets ? { datasets: [{ id: "raw", external: true }, { id: "clean" }], runs: [{ id: "job1", job: "normalize", used: ["raw"], generated: ["clean"], verified: true }] } : {})) === JSON.stringify(good) && Object.isFrozen(good), "PROV deterministic + frozen");
  // integration: runReferenceProject carries provenanceGraph and degrades on a broken graph.
  const integ = P4.runReferenceProject({ provenanceGraph: { datasets: [{ id: "mystery" }, { id: "out" }], runs: [{ id: "j", used: ["mystery"], generated: ["out"] }] } });
  check(integ.provenanceGraph && integ.provenanceGraph.ok === false && integ.degraded === true, "integration: a broken provenance graph ⇒ degraded (true)");
}

console.log(failures === 0 ? "ALL PASS — V12.4 §43 P4 DATA REFERENCE" : `FAILURES: ${failures}`);
process.exit(failures === 0 ? 0 : 1);
export {};
