/*
 * V12.4 / ODG LOCAL INTELLIGENCE ENGINE — L3 GOVERNED NATIVE REPAIR (§4/§6). PURE, deterministic. The SCORING + GOVERNANCE
 * core for applying a LOCALLY-generated repair to a REAL tracked repository file through the governed write-set guard.
 * It does NOT call the model or write files here (that is the live, out-of-gate step): it (a) exposes `guardAuthorizes`
 * over the EXISTING `repair-workflow.makeWriteSetGuard` (reuse — no new confinement), and (b) scores the L3 chain,
 * declaring L3 PROVEN only when EVERY governed step succeeded: independent test FAILED before + PASSED after, the diff is
 * minimal, ONLY the authorized write-set changed, Truth Lock held, and rollback restored the original. Fail-closed: any
 * missing step ⇒ NOT L3. Claude Code does not write the repair; the local model generates it; the governed executor
 * applies it; the independent test (model-independent) verifies it. Dual export.
 */

const RW = require("./repair-workflow");

function isObj(v: any): boolean { return v !== null && typeof v === "object" && !Array.isArray(v); }
function arr(v: any): any[] { return Array.isArray(v) ? v : []; }

/** guardAuthorizes(writeSet, target) -> boolean. Reuses the real write-set guard (rejects out-of-set / '..' / absolute). */
function guardAuthorizes(writeSet: any, target: any): boolean {
  try { return RW.makeWriteSetGuard(arr(writeSet))(String(target)) === true; } catch { return false; }
}

/**
 * scoreL3({ testBefore, testAfter, diffMinimal, changedPaths, writeSet, truthLockHeld, rolledBack, modelGenerated }) ->
 *   { l3Proven, reasons }. L3 PROVEN only if the full governed chain succeeded (fail-closed).
 */
function scoreL3(input: any): any {
  const o = isObj(input) ? input : {};
  const reasons: string[] = [];
  const changed = arr(o.changedPaths).map(String);
  const guard = (p: string) => guardAuthorizes(o.writeSet, p);
  const unauthorizedChanged = changed.filter((p) => !guard(p));

  if (o.modelGenerated !== true) reasons.push("repair was not generated by the local model (Claude must not write it) ⇒ fail");
  if (o.testBefore !== "FAIL") reasons.push("independent test did not FAIL on the defect before repair ⇒ no real defect proven");
  if (o.testAfter !== "PASS") reasons.push("independent test did not PASS after the repair ⇒ repair not verified");
  if (o.diffMinimal !== true) reasons.push("diff is not minimal ⇒ change not bounded");
  if (unauthorizedChanged.length > 0) reasons.push(`files changed OUTSIDE the authorized write-set: ${unauthorizedChanged.join(", ")} ⇒ confinement breach`);
  if (o.truthLockHeld !== true) reasons.push("Truth Lock not confirmed held ⇒ fail-closed");
  if (o.rolledBack !== true) reasons.push("rollback did not restore the original ⇒ reversibility not proven");

  const l3Proven = reasons.length === 0;
  return Object.freeze({
    l3Proven,
    unauthorizedChanged: Object.freeze(unauthorizedChanged),
    reasons: Object.freeze(l3Proven ? ["full governed chain succeeded: model-generated repair, independent FAIL→PASS, minimal diff, write-set confined, Truth Lock held, rollback restored ⇒ L3 PROVEN"] : reasons),
  });
}

