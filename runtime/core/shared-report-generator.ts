#!/usr/bin/env node
"use strict";

/*
 * V12.4 / CTO V46.2 (O1) — SHARED REPORT GENERATOR. PURE, deterministic, fail-closed. ONE report layer for the 15 métiers:
 * it takes a NORMALIZED métier result (the MetierReport contract) and emits a structured JSON report + a PME-readable
 * Markdown report (exec summary, controls, findings/risks, recommendations, limits, evidence refs, final status +
 * validation conditions). It imposes NO métier rules, INVENTS no result, ALTERS no conclusion, and NEVER turns an absence
 * of proof into a success — a missing field is shown as "not provided". Evidence is attached via the shared-evidence-wrapper
 * (O2), which composes the canonical evidence-provenance primitive. Métier leaves stay decoupled (they pass a plain object).
 * Dual export.
 */

const EVID = require("./shared-evidence-wrapper.js");

function isObj(v: any): boolean { return v !== null && typeof v === "object" && !Array.isArray(v); }
function arr(v: any): any[] { return Array.isArray(v) ? v : []; }
function s(v: any, fallback = "(not provided)"): string { return (v === undefined || v === null || v === "") ? fallback : String(v); }

// The stable métier→report contract. Any métier fills this WITHOUT losing its specifics; O1 only formats it.
const METIER_REPORT_SCHEMA = Object.freeze({
  required: Object.freeze(["metier", "title", "status"]),
  shape: Object.freeze({ metier: "string", title: "string", summary: "string", controls: "[{name,status,detail}]", findings: "[{severity,detail,basis}]", recommendations: "[string]", limits: "[string]", evidence: "[{claim,basis,sourceRef}]", status: "string", validationConditions: "[string]" }),
});

/** generateReport(report, opts) -> { ok, json, markdown, evidence, missingRequired }. FAIL-CLOSED: missing required fields
 *  are reported (ok:false) but a best-effort report is still produced with "(not provided)" — never fabricated values. */
function generateReport(report: any, opts: any = {}): any {
  const r = isObj(report) ? report : {};
  const missing = METIER_REPORT_SCHEMA.required.filter((k) => r[k] === undefined || r[k] === null || r[k] === "");
  const controls = arr(r.controls).filter(isObj);
  const findings = arr(r.findings).filter(isObj);
  const recs = arr(r.recommendations).map(String);
  const limits = arr(r.limits).map(String);
  const evItems = arr(r.evidence).filter(isObj);
  const wrapped = EVID.wrapEvidence(evItems, isObj(opts) ? opts : {});   // O2 — canonical provenance, basis never upgraded

  const json = Object.freeze({
    metier: s(r.metier), title: s(r.title), status: s(r.status), summary: s(r.summary),
    controls: Object.freeze(controls.map((c) => ({ name: s(c.name), status: s(c.status), detail: s(c.detail, "") }))),
    findings: Object.freeze(findings.map((f) => ({ severity: s(f.severity, "INFO"), detail: s(f.detail), basis: EVID.BASIS.indexOf(String(f.basis).toUpperCase()) >= 0 ? String(f.basis).toUpperCase() : "UNKNOWN" }))),
    recommendations: Object.freeze(recs), limits: Object.freeze(limits),
    validationConditions: Object.freeze(arr(r.validationConditions).map(String)),
    evidence: wrapped, generator: "shared-report-generator (O1)", missingRequired: Object.freeze(missing),
  });

  const md: string[] = [
    `# ${json.title} — ${json.metier}`,
    ``, `> Generated by ODG's shared report layer (O1). **Status: ${json.status}.** This report FORMATS a métier result; it invents no finding and changes no conclusion. A "(not provided)" value means the métier did not supply it (never fabricated).`,
    ``, `## Executive summary`, s(r.summary, "(not provided)"),
    ``, `## Controls`, ...(controls.length ? json.controls.map((c: any) => `- **${c.name}**: ${c.status}${c.detail ? ` — ${c.detail}` : ""}`) : ["- (none provided)"]),
    ``, `## Findings & risks`, ...(findings.length ? json.findings.map((f: any) => `- [${f.severity}] ${f.detail} _(basis: ${f.basis})_`) : ["- (none provided)"]),
    ``, `## Recommendations`, ...(recs.length ? recs.map((x) => `- ${x}`) : ["- (none provided)"]),
    ``, `## Limits of this analysis`, ...(limits.length ? limits.map((x) => `- ${x}`) : ["- (none provided)"]),
    ``, `## Evidence (${wrapped.summary.total} items; ${wrapped.counts.PROVEN} PROVEN, ${wrapped.counts.SIMULATED} SIMULATED, ${wrapped.counts.UNKNOWN} UNKNOWN)`,
    ...(wrapped.items.length ? wrapped.items.map((e: any) => `- [${e.basis}] ${e.claim}${e.sourceRef ? ` — \`${e.sourceRef}\`` : ""}`) : ["- (none provided)"]),
    `- integrity digest (sha256): \`${(wrapped.integrity.digest || "n/a")}\` — independently verifiable via evidence-provenance.`,
    ``, `## Final status & validation conditions`, `- **${json.status}**`, ...(json.validationConditions.length ? json.validationConditions.map((x: string) => `- condition: ${x}`) : ["- (no explicit validation conditions provided)"]),
    ``, `_ODG maturity is per-métier; this layer asserts no capability of its own._`,
  ];

  return Object.freeze({ ok: missing.length === 0, json, markdown: md.join("\n") + "\n", evidence: wrapped, missingRequired: Object.freeze(missing) });
}

const SHARED_REPORT_GENERATOR_CONTRACT = Object.freeze({
  id: "V124-SHARED-REPORT-GENERATOR", source: "CTO V46.2 O1 — one report layer for the 15 métiers",
  reuses: Object.freeze(["shared-evidence-wrapper (O2) → evidence-provenance (canonical provenance)"]),
  notAuthority: "formats a normalized métier result into JSON + PME markdown; it invents no result, alters no conclusion, and turns no absence of proof into success",
  invariants: Object.freeze([
    "a missing required field ⇒ ok:false + '(not provided)' — never a fabricated value",
    "a finding's basis is carried through unchanged (UNKNOWN if unrecognized) — never upgraded",
    "evidence + integrity come from O2/evidence-provenance (no second source of truth); the report is independently verifiable",
    "métier business rules are NOT imposed; the leaf stays decoupled (passes a plain object); pure/deterministic",
  ]),
  schema: METIER_REPORT_SCHEMA,
});

module.exports = { METIER_REPORT_SCHEMA, generateReport, SHARED_REPORT_GENERATOR_CONTRACT };

if (require.main === module) {
  const rep = generateReport({ metier: "P3", title: "Demo", status: "PREPARED", summary: "x", findings: [{ severity: "MEDIUM", detail: "unknown license", basis: "PROVEN" }], evidence: [{ claim: "SBOM 485 comp", basis: "PROVEN", sourceRef: "P3.json" }], limits: ["readiness only"], validationConditions: ["independent verifier"] });
  process.stdout.write(JSON.stringify({ ...SHARED_REPORT_GENERATOR_CONTRACT, demo: { ok: rep.ok, mdLines: rep.markdown.split("\n").length, provenPct: rep.evidence.counts.PROVEN } }, null, 2) + "\n");
}

export {};
