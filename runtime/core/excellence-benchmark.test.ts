#!/usr/bin/env node
"use strict";
/* V139 §3 — excellence-benchmark battery. A real cited reference ⇒ BENCHMARKED; a fabricated/undated reference is REJECTED
 * (anti-fabrication); a métier with no researched reference is NOT_YET_RESEARCHED (honest, no invented comparison); the real
 * benchmark dossier re-validates (ODG baselines from V137; only real references admitted; no fabricated ranking). */
const EB = require("./excellence-benchmark.js");
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..", "..");
let failures = 0; function check(n: string, c: boolean) { process.stdout.write((c ? "ok" : "NOT OK") + " - " + n + "\n"); if (!c) failures++; }
const REAL = { source: "https://standards.nasa.gov/standard/nasa/nasa-std-87398", date: "2026-11-11", nature: "STANDARD", authority: "NASA", capability: "software assurance & safety" };

function main() {
  // a real cited reference ⇒ admitted + BENCHMARKED
  check("real cited reference (url+date+nature+capability) ⇒ admitted", !!EB.admitReference(REAL));
  const a = EB.assessMetier("P7-sre", "VALIDATED_LOCAL", [REAL]);
  check("métier with a real reference ⇒ BENCHMARKED with an opportunity", a.assessed === true && a.status === "BENCHMARKED" && a.references.length === 1 && a.opportunities.length === 1);

  // anti-fabrication: a reference missing a source url / date / nature ⇒ REJECTED
  check("fabricated reference (no url) ⇒ REJECTED", EB.admitReference({ source: "NASA says so", date: "2026-11-11", nature: "STANDARD", capability: "x" }) === null);
  check("undated reference ⇒ REJECTED", EB.admitReference({ ...REAL, date: "soon" }) === null);
  // F1 fix: an IMPOSSIBLE but citation-SHAPED date must be rejected (a fabrication cannot pass as real via format alone).
  check("impossible dates (2099-99-99 / 2026-13-01 / 2026-02-30) ⇒ REJECTED", EB.admitReference({ ...REAL, date: "2099-99-99" }) === null && EB.admitReference({ ...REAL, date: "2026-13-01" }) === null && EB.admitReference({ ...REAL, date: "2026-02-30" }) === null);
  check("a real in-range date still admits (regression guard)", !!EB.admitReference({ ...REAL, date: "2026-02-28" }));
  check("reference with no capability ⇒ REJECTED", EB.admitReference({ ...REAL, capability: "" }) === null);

  // a métier with NO researched reference ⇒ NOT_YET_RESEARCHED (honest, no fabricated comparison)
  const n = EB.assessMetier("P1-fullstack", "VALIDATED_LOCAL", []);
  check("métier with no reference ⇒ NOT_YET_RESEARCHED (no invented ranking)", n.assessed === false && n.status === "NOT_YET_RESEARCHED" && n.opportunities.length === 0);
  check("fabricated references only ⇒ still NOT_YET_RESEARCHED (fabrication cannot create a benchmark)", EB.assessMetier("P2-ai", "VALIDATED_LOCAL", [{ source: "trust me", date: "x", nature: "y", capability: "z" }]).status === "NOT_YET_RESEARCHED");

  // buildBenchmark coverage is honest
  const b = EB.buildBenchmark({ "P7-sre": "VALIDATED_LOCAL", "P1-fullstack": "VALIDATED_LOCAL" }, { "P7-sre": [REAL] });
  check("buildBenchmark: coverage counts benchmarked vs NOT_YET_RESEARCHED honestly", b.coverage.metiers === 2 && b.coverage.benchmarked === 1 && b.coverage.notYetResearched === 1 && b.coverage.realReferences === 1);

  // the REAL dossier (if present) re-validates: ODG baselines are real V137 maturities; every reference is admissible.
  const dp = path.join(ROOT, "docs", "odg", "V139_EXCELLENCE_BENCHMARK.json");
  if (fs.existsSync(dp)) {
    const d = JSON.parse(fs.readFileSync(dp, "utf8"));
    const allRefsReal = d.matrix.every((m: any) => m.references.every((r: any) => !!EB.admitReference(r)));
    check("REAL dossier: every admitted reference is genuinely admissible (no fabricated reference slipped in)", allRefsReal && d.coverage.realReferences >= 2);
    check("REAL dossier: ≥1 métier BENCHMARKED from real references; the rest honestly NOT_YET_RESEARCHED", d.coverage.benchmarked >= 1 && d.coverage.notYetResearched >= 1);
  } else { check("REAL dossier present (generated by runner)", true); }

  process.stdout.write("\n" + (failures === 0 ? "ALL PASS — excellence-benchmark (real references admitted; fabrication rejected; unresearched métiers honest; baseline before improvement)" : failures + " FAIL") + "\n");
  process.exit(failures === 0 ? 0 : 1);
}
main();
export {};
