/* oracle test file — authored by ODG RULES from the computed oracle (deterministic; not model, not hand-written) */
function oracleTestSource(oracle: any): string {
  const all = oracle.repairExamples.map((r: any) => ({ args: r.args, expect: r.expect })).concat(oracle.acceptanceCases.map((c: any) => ({ args: c.args, expect: c.expect })));
  return [
    "#!/usr/bin/env node",
    "\"use strict\";",
    `/* GENERATED by ODG rules (runtime/core/odg-native-repair-item.ts ORC-1/REF-1) — oracle sha256 ${oracle.sha256}; expected values computed`,
    ` * by executing the in-repo reference canon() (sha256 ${oracle.referenceSha256}). Not model-authored, not hand-written. */`,
    `const M = require("./odg-canonical-json.js");`,
    `const CASES: any[] = ${JSON.stringify(all)};`,
    "let failures = 0;",
    `CASES.forEach((c: any, i: number) => { const got = M.${NRI.EXPORT_NAME}(c.args[0]); const ok = got === c.expect; process.stdout.write((ok ? "ok" : "NOT OK") + " - case " + i + " " + JSON.stringify(c.args[0]) + "\\n"); if (!ok) failures++; });`,
    "if (failures) { process.stdout.write(failures + \" failure(s)\\n\"); process.exit(1); }",
    "export {};",
    "",
  ].join("\n");
}
