/* ---------------- the local-model seam (prompt for a TS module; same Ollama call shape as local-model-generator) ---- */
function buildPrompt(fileSpec: any): string {
  const lines = [
    "You are writing exactly ONE TypeScript source file for a strict TypeScript repository that uses CommonJS.",
    "Output ONLY the TypeScript source. No explanation, no markdown fences, no prose.",
    "Requirements: no import statements; annotate every parameter and return type (use `any` for the value);",
    "export with module.exports = { ... }; and put `export {};` as the LAST line of the file.",
    "",
    `File: ${NRI.TARGET_MODULE}`,
    "Contract (must be satisfied exactly):",
    String(fileSpec.contract || ""),
  ];
  if (fileSpec.buildError) lines.push("", "A previous attempt FAILED to build with this error — fix it:", "  " + String(fileSpec.buildError));
  if (fileSpec.verifyError) lines.push("", "A previous attempt BUILT but FAILED the functional test — fix the LOGIC:", "  " + String(fileSpec.verifyError));
  if (fileSpec.typeError) lines.push("", "A previous attempt PASSED the tests but FAILED the strict TypeScript typecheck — fix the types:", "  " + String(fileSpec.typeError));
  lines.push("", "Now output only the code:");
  return lines.join("\n");
}
function makeGenerator(fetchImpl: any, log: any[], round: number, extraHint: any): any {
  return async function generateFile(fileSpec: any): Promise<any> {
    const spec = { ...fileSpec, ...(extraHint && !fileSpec.buildError && !fileSpec.verifyError ? extraHint : {}) };
    const prompt = buildPrompt(spec);
    const t0 = Date.now();
    const rec: any = { round, i: log.length + 1, model: BUDGETS.model, promptSha256: sha256(prompt), hint: spec.buildError ? "buildError" : spec.verifyError ? "verifyError" : spec.typeError ? "typeError" : null };
    log.push(rec);
    try {
      const ctl = new AbortController(); const timer = setTimeout(() => ctl.abort(), BUDGETS.perCallTimeoutMs);
      let res: any; try { res = await fetchImpl(`http://${OLLAMA.host}:${OLLAMA.port}/api/generate`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ model: BUDGETS.model, prompt, stream: false }), signal: ctl.signal }); } finally { clearTimeout(timer); }
      rec.ms = Date.now() - t0;
      if (!res || res.ok !== true) { rec.ok = false; rec.reason = `HTTP ${res && res.status}`; return { ok: false }; }
      const j = await res.json();
      rec.evalCount = (j && j.eval_count) || null; rec.respondedModel = (j && j.model) || null;
      const tsSrc = GEN.extractCode(j && j.response);       // canonical fence-stripping + module check (fail-closed)
      if (!tsSrc) { rec.ok = false; rec.reason = "no CommonJS module extracted"; rec.raw = String((j && j.response) || "").slice(0, 2000); return { ok: false }; }
      const t = transpile(tsSrc);
      rec.ok = true; rec.tsSource = tsSrc; rec.tsSha256 = sha256(tsSrc); rec.syntaxErrors = t.syntaxErrors;
      // syntax errors ⇒ hand the RAW source to the sandbox so the build fails with the real parser message (repair hint)
      const content = t.syntaxErrors.length ? tsSrc : t.js;
      rec.sandboxContentSha256 = sha256(content);
      return { ok: true, content };
    } catch (e: any) { rec.ms = Date.now() - t0; rec.ok = false; rec.reason = String((e && e.message) || e).slice(0, 300); return { ok: false }; }
  };
}

