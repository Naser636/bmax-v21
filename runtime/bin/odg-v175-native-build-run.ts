/* ---------------- the native build ---------------- */
async function runNativeBuild(opts: any): Promise<any> {
  const root = opts.root || ROOT;
  const t0 = Date.now();
  const detection = NRI.detectCanonDefects(root);
  const oracle = NRI.buildOracle(detection);
  const base: any = { schema: "odg-native-build-result/1", label: opts.label, scenario: SCENARIO, contractSha256: opts.contractSha256 || null, nativeClaim: NATIVE_CLAIM, run: { head: headOf(root), startedAt: new Date(t0).toISOString(), runner: SELF }, budgets: BUDGETS,
    detection: { defect: detection.defect, defectClass: detection.defectClass, evidenceDigest: detection.evidenceDigest, defectiveSites: detection.defectiveSites, reference: detection.reference, scanned: detection.scanned, targetExists: detection.targetExists } };
  const finish = (x: any) => ({ ...base, ...x, outcome: x.verdict, wallMs: Date.now() - t0 });   // outcome = verdict (R4 experiment record field)
  if (!detection.defect || !oracle) return finish({ verdict: "NOT_MEASURED", reason: detection.targetExists ? "target module already exists — nothing to build" : "no defect detected / no reference (nothing to repair)" });
  if (opts.expectedDigest && opts.expectedDigest !== detection.evidenceDigest) return finish({ verdict: "NOT_MEASURED", reason: `AC5 detection drift: fresh evidenceDigest ${detection.evidenceDigest} ≠ contract ${opts.expectedDigest}` });
  if (opts.expectedOracleSha && opts.expectedOracleSha !== oracle.sha256) return finish({ verdict: "NOT_MEASURED", reason: `oracle drift: ${oracle.sha256} ≠ contract ${opts.expectedOracleSha}` });

  const guard = makeGuard(opts.transport);
  const generations: any[] = [];
  const rounds: any[] = [];
  const spec: any = {
    name: "V175-NB1 odg-canonical-json",
    architecture: [{ path: NRI.SANDBOX_FILE, role: "shared canonical-JSON serializer", contract: NRI.MODULE_SPEC, dependsOn: [] }],
    writeSet: [NRI.SANDBOX_FILE], entry: NRI.SANDBOX_FILE,
    independentTestCases: oracle.acceptanceCases,
    repairExamples: oracle.repairExamples.map((r: any) => ({ args: r.args, expect: r.expect })),
  };
  let accepted: any = null; let extraHint: any = null;
  for (let round = 1; round <= BUDGETS.maxRounds && !accepted; round++) {
    const out = await BUILDER.buildProject(spec, { generateFile: makeGenerator(guard.fetchImpl, generations, round, extraHint), maxRepair: BUDGETS.maxRepairPerRound, sandboxRunner: opts.sandboxRunner });
    const finalJs = out.files ? out.files[NRI.SANDBOX_FILE] : null;
    const gen = [...generations].reverse().find((g: any) => g.round === round && g.ok && g.sandboxContentSha256 === (finalJs ? sha256(finalJs) : null));
    const r: any = { round, buildOk: out.buildOk, verified: out.verified, accepted: out.accepted, repairs: out.repairs, repairStopReason: out.repairStopReason, verifyError: out.verifyError, buildError: out.buildError, executionMode: out.executionMode, executionStatus: out.executionStatus, isolation: out.isolation, firstPass: out.firstPass, finalTsSha256: gen ? gen.tsSha256 : null };
    rounds.push(r);
    if (out.executionStatus !== "EXECUTED" || out.executionMode !== "SANDBOX") { r.typecheck = null; break; }
    if (out.accepted && gen) {
      r.typecheck = typecheck(gen.tsSource);
      if (r.typecheck.ok) accepted = gen; else extraHint = { typeError: r.typecheck.diagnostics.join(" | ") };
    }
    if (guard.st.capHit) break;
  }
  const network = { modelCalls: guard.st.modelCalls, prompts: guard.st.prompts, refused: guard.st.refused, capHit: guard.st.capHit, providerCalls: 0 };
  const notMeasured = guard.st.refused.length > 0 || rounds.some((r: any) => r.executionStatus !== "EXECUTED" || r.executionMode !== "SANDBOX");
  const provenance = { actor: "ODG", executionClass: NE.EXEC.LOCAL, patchAuthoredBy: `local model ${BUDGETS.model} via Ollama 127.0.0.1:11434`, testAuthoredBy: "ODG_RULES (oracleTestSource from ORC-1/REF-1)", runnerAuthoredBy: "PROVIDER (Claude Code) — plumbing only", providerEditedGeneratedCode: false, providerCalls: 0 };
  if (notMeasured) return finish({ verdict: "NOT_MEASURED", reason: guard.st.refused.length ? "non-loopback request refused" : "sandbox did not execute (NOT_RUN) — no verdict", rounds, generations, network, provenance });
  if (!accepted) return finish({ verdict: "FAIL", reason: `no generation passed AC1+AC2 within ${BUDGETS.maxRounds} rounds × (1 + ${BUDGETS.maxRepairPerRound} repairs)${guard.st.capHit ? " (cap " + guard.st.capHit + ")" : ""}`, rounds, generations, network, provenance });
  const testSrc = oracleTestSource(oracle);
  const diff = newFileDiff(NRI.TARGET_MODULE, accepted.tsSource) + newFileDiff(NRI.TARGET_TEST, testSrc);
  const applyCheck = gitApplyCheck(root, diff);
  const patch = { files: [{ path: NRI.TARGET_MODULE, sha256: sha256(accepted.tsSource), authoredBy: "LOCAL_MODEL", generation: accepted.i }, { path: NRI.TARGET_TEST, sha256: sha256(testSrc), authoredBy: "ODG_RULES" }], diff, diffSha256: sha256(diff), gitApplyCheck: applyCheck };
  return finish({ verdict: applyCheck.ok ? "PASS" : "FAIL", reason: applyCheck.ok ? "AC1 held-out oracle PASS in sandbox + AC2 strict typecheck PASS + AC3 git apply --check OK" : "AC3 failed: diff does not apply", rounds, generations, network, provenance, patch,
    integration: "OWNER_GATED: apply patch.diff on a branch and open a PR (no checkout is written by this runner); migrating audit-log / agent-identity / supply-chain-attest to the helper changes persisted hash/signature preimages ⇒ separate owner decision" });
}

