#!/usr/bin/env node
"use strict";
/*
 * V12.4 cont. (V360 P1) — KNOWLEDGE-ENGINE RUN (runtime entry). The PRIORITY-1 inventory flagged knowledge-engine as
 * require-graph ORPHAN; the truth is subtler: it is a SIDE-EFFECTING PRODUCER (walks src/ + runtime/, reads
 * execution-plan + capability-registry, writes runtime/generated/knowledge.json at load) whose ARTIFACT is already
 * consumed by real modules — decision-engine (optional, non-driving context) and stage-effect. The missing link was a
 * reproducible RUN path: nothing regenerated the artifact. This bin provides it — it invokes the engine (regenerating
 * knowledge.json) and reports the graph summary, so the producer→artifact→consumer chain is a real, repeatable execution
 * path. Reads/writes only the generated artifact; no new engine, no second knowledge store.
 *
 * Usage: npx tsx runtime/bin/odg-knowledge-engine-run.ts
 */
const path = require("path");
const fs = require("fs");
const ROOT = path.join(__dirname, "..", "..");
const KJSON = path.join(ROOT, "runtime", "generated", "knowledge.json");

// requiring the engine triggers its load-time generation (walk → write knowledge.json). Isolated side effect, dev-only artifact.
try { require(path.join(ROOT, "runtime", "core", "knowledge-engine.js")); }
catch (e: any) { process.stdout.write("KNOWLEDGE-ENGINE RUN FAILED: " + String((e && e.message) || e) + "\n"); process.exit(1); }

let k: any = null;
try { k = JSON.parse(fs.readFileSync(KJSON, "utf8")); } catch { /* reported below */ }
if (!k) { process.stdout.write("knowledge.json not produced\n"); process.exit(1); }

const n = (v: any) => (Array.isArray(v) ? v.length : (v && typeof v === "object" ? Object.keys(v).length : v));
process.stdout.write(JSON.stringify({
  ran: "knowledge-engine", artifact: "runtime/generated/knowledge.json",
  mission: k.mission ?? null, status: k.status ?? null,
  knownCapabilities: n(k.knownCapabilities), missingCapabilities: n(k.missingCapabilities),
  todo: k.TODO ?? k.todo ?? null, fixme: k.FIXME ?? k.fixme ?? null,
  consumedBy: ["decision-engine (optional non-driving context)", "stage-effect"],
}, null, 2) + "\n");
process.stdout.write("\nOK — knowledge.json regenerated by the engine (producer in a real, repeatable path; artifact consumed by decision-engine + stage-effect).\n");
process.exit(0);
export {};
