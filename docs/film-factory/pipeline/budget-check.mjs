import { readFileSync } from "node:fs";
const B = JSON.parse(readFileSync(new URL("./budget-register.json", import.meta.url),"utf8"));
let p=0,f=0; const ck=(n,c)=>{console.log((c?"PASS ":"FAIL ")+n);c?p++:f++;};
ck("cap is €2000", B.cap===2000);
ck("ceilings sum ≤ €2000", B.totals.ceilingsSum<=2000 && B.totals.ceilingsWithinCap);
ck("allocatedEstimate ≤ cap", B.totals.allocatedEstimateSum<=2000 && B.totals.allocWithinCap);
ck("committed €0 and spent €0 (nothing engaged)", B.totals.committedEur===0 && B.totals.spentEur===0);
ck("remaining = cap (no spend)", B.totals.remainingEur===2000);
ck("every envelope allocatedEstimate ≤ its ceiling", B.envelopes.every(e=>e.allocatedEstimate<=e.ceiling && e.withinCeiling));
ck("every envelope costStatus=ESTIMATED (none MEASURED)", B.envelopes.every(e=>e.costStatus==="ESTIMATED"));
ck("benchmark envelope revised to €250 (≤ old €350)", B.envelopes.find(e=>e.id==="benchmark_tool_select").ceiling===250);
ck("pre-spend checks listed (licence/taxes/recurring/expiry/cancellation)", B.checksToVerify.length>=5);
console.log(`\nBUDGET-2000 CHECKS: ${f===0?"PASS":"FAIL"} (pass=${p} fail=${f})`);
process.exit(f?1:0);
