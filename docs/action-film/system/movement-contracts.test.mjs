import { validateContract, repetitiveActions, CONTRACT_FIELDS } from './movement-contracts.mjs';
import { readFileSync } from 'node:fs'; import { fileURLToPath } from 'node:url'; import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const design = JSON.parse(readFileSync(join(here, '../design/film-design-v1.json'), 'utf8'));
let pass = 0, fail = 0; const fails = [];
const ok = (n, c) => { if (c) pass++; else { fail++; fails.push(n); } };
ok('6 contract fields defined', CONTRACT_FIELDS.length === 6);
ok('design movement contracts all valid', design.movementContracts.every(c => validateContract(c).valid));
ok('incomplete contract flagged (4 fields missing)', validateContract({ initial: 'veig low guard mid-ford', trajectory: 'overhead cut parried' }).missing.length === 4);
ok('trivial-length values rejected (all 6 missing)', validateContract({ initial: 'a', trajectory: 'b' }).missing.length === 6);
ok('no repetition in the 2 distinct design beats', repetitiveActions(design.movementContracts).length === 0);
ok('identical beats flagged as repetitive', repetitiveActions([{ beat: 'x', trajectory: 'overhead cut', contact: 'parry' }, { beat: 'y', trajectory: 'overhead cut', contact: 'parry' }]).length === 1);
console.log('MOVEMENT-CONTRACT TESTS: ' + (fail === 0 ? 'PASS' : 'FAIL') + ' (pass=' + pass + ' fail=' + fail + ')' + (fail ? ' [' + fails.join(', ') + ']' : ''));
process.exit(fail === 0 ? 0 : 1);
